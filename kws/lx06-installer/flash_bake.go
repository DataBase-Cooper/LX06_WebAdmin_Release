package main

// 刷机前 SSH 配置烘焙（固件与 SSH 合并为同一镜像）：
//
//	构建期（一次性，WSL，scripts/build_ssh_base.sh）：
//	  official-ssh/root.squashfs 是「完整官方固件 1.94.13 + SSH」的自包含镜像：
//	    官方 root.squashfs（1348 文件 + 673 符号链接）
//	    + /usr/lib/lx06/{ssh-apply,ssh-watch,init-launch}.sh
//	    + /etc/init.d/boot 的 boot() 末尾钩子
//	    + /lx06-ssh-default.conf（端口 89 / root 密码 DB_COOPER / 仅局域网，
//	      用户刷机弹窗不填时的保底默认；用户填了则 /lx06-ssh.conf 覆盖它）。
//	  钩子负责首启读 conf 写 /data/ssh_en=1、bind-mount dropbear 配置与 shadow、
//	  等 LAN IP 后确保 dropbear 在线，并把 /lx06-init.d/* 拷到 /data/init.d/ 自启。
//
//	刷机期（用户机器，零依赖，本文件）：
//	  1. 预拷贝 official-ssh/root.squashfs（包自己的镜像，已含钩子+默认 conf）
//     为 out.img
//	  2. tools/mksquashfs.exe <src> out.img（输出已存在 → append 合并，~1s）
//	     src 顶层只放 NEW 路径（/lx06-ssh.conf 用户配置、/lx06-init.d/ 自启程序），
//	     与 base 根目录不同名 → 不触发 mksquashfs「同名旧文件胜出、新文件 *_1」改名。
//	  3. update.exe partition system0 out.img
//
// 刷完后设备首次开机即按配置启动 SSH —— 全程不需要音箱 IP，不需要刷后 SSH 回连。
// 用户机器只依赖 tools/mksquashfs.exe（静态 ~1.7MB）。
// append 只新增文件，base 的 673 个符号链接与全部官方文件原样保留。

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

const (
	bakedConfName = "lx06-ssh.conf"  // 刷机期 append：镜像顶层 /lx06-ssh.conf（用户配置）
	bakedSeqName  = "lx06-ssh-seq"   // 刷机期 append：本次刷机的唯一序号
	bakedInitDir  = "lx06-init.d"    // 刷机期 append：镜像顶层 /lx06-init.d/（自启程序）
	bakedOutName  = "lx06-system0.img"
	// 日志传送目标（刷机期 append，与 /lx06-ssh.conf 同机制）：
	// base 镜像顶层不含 /lx06-log.conf，append 不会触发 mksquashfs *_1 改名。
	bakedLogConfName = "lx06-log.conf" // 本机内网 IPv4 + 端口 87（设备端 log-seed.sh 播种）
	bakedLogSeqName  = "lx06-log-seq"  // 复用本次刷机序号（log-seed.sh 比对用）
)

// bakedBasePath 返回烘焙 SSH 配置所用的 base 镜像 = official-ssh 包自己的
// root.squashfs（构建期已合并 SSH 钩子 + 默认 conf 的自包含完整镜像）。
// 刷机时 append 的用户配置 /lx06-ssh.conf 与 /lx06-init.d/ 都是与 base 根
// 目录不同名的 NEW 路径，因此不会触发 mksquashfs 的 *_1 改名。
// （preflightPackage 已先校验该镜像 SHA256，正常刷机时必然存在；缺失时
//
//	bakeSSHConf 会给出明确错误。）
func (a *App) bakedBasePath(pkg FwPackage) string {
	return filepath.Join(pkg.Dir, pkg.Firmware)
}

// mksquashfsExe 返回随包携带的 mksquashfs 工具（刷机期 append 用）。
// 主路径 tools/（release 包布局）；回退 ../tools/ 与 exe 同目录（dev 的
// build/ 布局下 tools 可能只放在源码根），两处都查，找不到才报错。
func (a *App) mksquashfsExe() string {
	cand := []string{
		filepath.Join(a.root, "tools", "mksquashfs.exe"),
		filepath.Join(a.root, "..", "tools", "mksquashfs.exe"),
	}
	for _, p := range cand {
		if _, err := os.Stat(p); err == nil {
			return filepath.Clean(p)
		}
	}
	return cand[0]
}

// bakeSSHConf 生成刷机期追加进镜像的顶层文件集，并把 base 预拷贝为 out.img：
//
//	lx06-ssh.conf    port/root password hash/LAN-only (device ssh.sh parses)
//	lx06-init.d/*    开机自启程序（设备端 init-launch.sh 拷到 /data/init.d/）
//
// 返回 (outImg, tmpDir, err)：outImg 已预拷贝 base、待 mksquashfs append 合并；
// tmpDir 是烘焙临时目录（调用方负责清理）。
func (a *App) bakeSSHConf(pkg FwPackage, cfg SSHConfig, initApps []InitApp, logf func(string, ...any)) (outImg, tmpDir string, err error) {
	base := a.bakedBasePath(pkg)
	if fi, e := os.Stat(base); e != nil {
		return "", "", fmt.Errorf("SSH base 镜像缺失: %s（official-ssh/root.squashfs 应随包携带）", base)
	} else {
		logf("SSH base 镜像: %s (%.1f MB)", filepath.Base(base), float64(fi.Size())/1048576)
	}
	if _, e := os.Stat(a.mksquashfsExe()); e != nil {
		return "", "", fmt.Errorf("mksquashfs 工具缺失: %s（应随包携带 tools/mksquashfs.exe）", a.mksquashfsExe())
	}

	if e := os.MkdirAll(a.dataDir, 0o755); e != nil {
		return "", "", fmt.Errorf("创建数据目录失败: %w", e)
	}
	tmp, err := os.MkdirTemp(a.dataDir, "lx06-bake-")
	if err != nil {
		return "", "", fmt.Errorf("创建烘焙临时目录失败: %w", err)
	}
	src := filepath.Join(tmp, "src")
	if err := os.MkdirAll(filepath.Join(src, bakedInitDir), 0o755); err != nil {
		os.RemoveAll(tmp)
		return "", "", err
	}

	// ---- /lx06-ssh.conf ----
	// V19 零配置：恒 22 / DB_COOPER / 仅局域网。cfg 参数保留仅用于日志溯源；
	// 实际烘焙值一律取 fixedSSHConfig()（调用方 app.go 也已固定，双保险）。
	fixed := fixedSSHConfig()
	var conf strings.Builder
	conf.WriteString("# generated by LX06Installer — read by /usr/lib/lx06/ssh.sh on first boot\n")
	conf.WriteString("ssh_port=" + strconv.Itoa(fixed.Port) + "\n")
	conf.WriteString("ssh_root_hash=" + md5CryptHash(fixed.Password, randomSalt()) + "\n")
	conf.WriteString("ssh_lan_only=1\n")
	if err := os.WriteFile(filepath.Join(src, bakedConfName), []byte(conf.String()), 0o644); err != nil {
		os.RemoveAll(tmp)
		return "", "", err
	}
	if (cfg.Port != fixed.Port) || (cfg.Password != fixed.Password) || !cfg.LANOnly {
		logf("SSH 配置归一: 入参(%d/%s/lan=%v) → 固定(89/DB_COOPER/lan=1)", cfg.Port, cfg.Password, cfg.LANOnly)
	}

	// ---- /lx06-ssh-seq ----
	// 每次刷机写入唯一序号。设备端 ssh.sh 把它与 /data/lx06-ssh-seq 比对：
	// 不同 = 这是一次新刷机 → 用本次刷机参数重 seed /data/lx06-ssh.conf；
	// 相同（未重刷、仅重启/断电恢复）→ /data 保持用户手工修改不变。
	seq := strconv.FormatInt(time.Now().UnixNano(), 10)
	if err := os.WriteFile(filepath.Join(src, bakedSeqName), []byte(seq+"\n"), 0o644); err != nil {
		os.RemoveAll(tmp)
		return "", "", err
	}

	// ---- /lx06-log.conf + /lx06-log-seq ----
	// 日志传送目标：刷机这台机器的内网 IPv4 + 系统推荐端口 87（用户定案，
	// 无需用户设置）。设备端 S10 boot 钩子（独立于 /data/init.sh）调
	// log-seed.sh 把本文件播种到 /data/lx06-log.conf；S70 看门狗在
	// 88/89 双死异常重启前把系统日志 POST 到该地址，由本工具 87 端口
	// 接收（log_recv.go）。Web 88 X×5 隐藏弹窗（/api/logconf）可改。
	// IP 探测失败 → 留空：seed 校验不过 → 不播种 → 不发送（fail-open）。
	lanIP := detectLanIPv4()
	if lanIP == "" {
		logf("警告: 未取到本机内网 IPv4，设备刷完后默认不发送日志（可在 Web 88 X×5 弹窗补填）")
	} else {
		logf("烘焙日志传送目标: %s:%d（本机内网 IP + 推荐端口）", lanIP, logRecvPort)
	}
	var lc strings.Builder
	lc.WriteString("# generated by LX06Installer — S70 watchdog reads before reboot (Web X×5 可改)\n")
	lc.WriteString("log_server_ip=" + lanIP + "\n")
	lc.WriteString("log_server_port=" + strconv.Itoa(logRecvPort) + "\n")
	lc.WriteString("log_enabled=1\n")
	lc.WriteString("log_max_kb=128\n")
	if err := os.WriteFile(filepath.Join(src, bakedLogConfName), []byte(lc.String()), 0o644); err != nil {
		os.RemoveAll(tmp)
		return "", "", err
	}
	if err := os.WriteFile(filepath.Join(src, bakedLogSeqName), []byte(seq+"\n"), 0o644); err != nil {
		os.RemoveAll(tmp)
		return "", "", err
	}

	// ---- /lx06-init.d/* ----
	for _, ap := range initApps {
		data, err := os.ReadFile(filepath.Join(a.root, initAppLocalDir, ap.Name))
		if err != nil {
			os.RemoveAll(tmp)
			return "", "", fmt.Errorf("读取 init-apps/%s 失败: %w", ap.Name, err)
		}
		// CRLF 铁律：.sh 必须是纯 LF（CRLF 的 `2>&1\r` → ash redir error →
		// 脚本 rc=2 中断 → keeper descendant-abnormal-exit 误入安全模式）。
		if strings.HasSuffix(ap.Name, ".sh") {
			data = bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n"))
		}
		if err := os.WriteFile(filepath.Join(src, bakedInitDir, ap.Name), data, 0o644); err != nil {
			os.RemoveAll(tmp)
			return "", "", err
		}
		logf("烘焙开机自启程序: %s (%d 字节)", ap.Name, len(data))
	}

	// ---- 预拷贝 base 为 out.img（mksquashfs 靠「输出已存在」判定 append）----
	outImg = filepath.Join(tmp, bakedOutName)
	if err := copyFile(base, outImg); err != nil {
		os.RemoveAll(tmp)
		return "", "", fmt.Errorf("预拷贝 base 镜像失败: %w", err)
	}
	logf("base 镜像预拷贝完成（%d 字节），开始 append 合并…", fileSize(outImg))
	// 立即合并（~1s），成功后 outImg 即最终写入 system0 的镜像。
	if err := a.mksquashfsAppend(src, outImg, logf); err != nil {
		os.RemoveAll(tmp)
		return "", "", err
	}
	return outImg, tmp, nil
}

// mksquashfsAppend 执行刷机期合并：mksquashfs.exe src out.img …
// 关键1：不带 -noappend（该标志会强制全新重建，丢掉 base —— A/B 实测坐实）。
// 关键2：必须带 -no-recovery。该 mksquashfs（squashfs-tools 4.x / sqfstar 变体）
// 默认把恢复文件写到 $HOME 下、文件名内嵌源路径；Windows 反斜杠源路径会生成
// 含 \ 的非法文件名 → create 返回 EINVAL → "Failed to create recovery file"
// 整个 append 中止（2026-09-26 本机 go run 实测复现，加 -no-recovery 后 rc=0）。
// append 是单次原子写，失败即整体重刷，恢复文件没有意义。
func (a *App) mksquashfsAppend(src, outImg string, logf func(string, ...any)) error {
	args := []string{
		src, outImg,
		"-comp", "xz", "-b", "131072",
		"-all-root", "-always-use-fragments", "-no-xattrs", "-no-exports",
		"-no-recovery",
	}
	logf("执行: mksquashfs.exe <src> %s -comp xz -b 131072 …", bakedOutName)
	cmd := exec.Command(a.mksquashfsExe(), args...)
	cmd.Dir = filepath.Dir(a.mksquashfsExe())
	hideProcess(cmd)
	var buf bytes.Buffer
	cmd.Stdout = &buf
	cmd.Stderr = &buf
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("mksquashfs 合并失败: %v (%s)", err, tailLines(buf.String(), 5))
	}
	// 合并后的镜像必须接近 base 大小（几 MB~几十 MB），而不是只有新文件（几 KB）。
	if fi, e := os.Stat(outImg); e != nil || fi.Size() < 10<<20 {
		return fmt.Errorf("合并结果异常（%d 字节，远小于 base）——append 未生效", fi.Size())
	}
	logf("镜像合并完成（%d 字节，base 内容 + SSH 配置 + 自启程序）", fileSize(outImg))
	return nil
}

func fileSize(p string) int64 {
	fi, err := os.Stat(p)
	if err != nil {
		return 0
	}
	return fi.Size()
}

func tailLines(s string, n int) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return strings.Join(lines, " | ")
}

// copyFile 复制文件（保留内容即可，权限在设备端由钩子脚本 chmod）。
func copyFile(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	return os.WriteFile(dst, data, 0o644)
}
