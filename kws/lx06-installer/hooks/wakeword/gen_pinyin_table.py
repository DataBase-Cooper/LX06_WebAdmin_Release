#!/usr/bin/env python3
"""Regenerate wake_pinyin_table.h from pypinyin (MIT) GB2312 first readings.

The table is pronunciation data, not a user lexicon. No device recordings.
"""
from pathlib import Path
from pypinyin import Style, lazy_pinyin

HERE = Path(__file__).resolve().parent


def main():
    syllables = []
    index = {}
    cps = []
    ids = []
    for lead in range(0xB0, 0xF8):
        for trail in range(0xA1, 0xFF):
            try:
                char = bytes((lead, trail)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            reading = lazy_pinyin(char, style=Style.NORMAL, errors=lambda _xs: [])
            if not reading:
                continue
            syllable = "".join(ch for ch in reading[0].lower() if ch.isalpha())
            if not syllable:
                continue
            if syllable not in index:
                index[syllable] = len(syllables)
                syllables.append(syllable)
            cps.append(ord(char))
            ids.append(index[syllable])
    order = sorted(range(len(cps)), key=lambda i: cps[i])
    cps = [cps[i] for i in order]
    ids = [ids[i] for i in order]
    lines = [
        "/* Toneless single-character readings for GB2312 hanzi.",
        " * Generated by gen_pinyin_table.py from pypinyin (MIT) first reading.",
        " * Not a user lexicon. Regenerate with that script; do not hand-edit. */",
        "#ifndef WAKE_PINYIN_TABLE_H",
        "#define WAKE_PINYIN_TABLE_H",
        f"#define WAKE_PY_SYLLABLES {len(syllables)}",
        f"#define WAKE_PY_CHARS {len(cps)}",
        "static const char *const wake_py_syllables[WAKE_PY_SYLLABLES] = {",
    ]
    row = []
    for syllable in syllables:
        row.append(f'"{syllable}"')
        if len(row) == 12:
            lines.append("  " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("  " + ", ".join(row) + ",")
    lines.append("};")

    def dump(name, values):
        lines.append(f"static const unsigned short {name}[WAKE_PY_CHARS] = {{")
        row_n = []
        for value in values:
            row_n.append(str(value))
            if len(row_n) == 16:
                lines.append("  " + ", ".join(row_n) + ",")
                row_n = []
        if row_n:
            lines.append("  " + ", ".join(row_n) + ",")
        lines.append("};")

    dump("wake_py_cp", cps)
    dump("wake_py_id", ids)
    lines.append("#endif")
    path = HERE / "wake_pinyin_table.h"
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path} syllables={len(syllables)} chars={len(cps)}")


if __name__ == "__main__":
    main()
