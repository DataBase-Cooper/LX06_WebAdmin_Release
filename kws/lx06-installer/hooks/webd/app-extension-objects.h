    if(index<0||(unsigned)index!=w->count||w->count>=EO_NODES||(frame?frame->index:-1)!=parent)return -1;
    int key=frame&&frame->kind==EO_OBJECT&&!(frame->children&1u);
    if(key&&type!=XZ_JSON_STRING)return -1;
