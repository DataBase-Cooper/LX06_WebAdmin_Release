/* A owns one allocation: header, exact node array, exact decoded strings.
 * These views are borrowed only; consumers must not shallow-copy, construct,
 * resize or free one. Formal maximum capacities are unchanged. */
struct eo_view {
    struct eo_node *nodes; char *strings; int64_t *numbers;
    unsigned count,used; int root,flows,schedules;
    unsigned node_capacity,string_capacity,number_capacity; size_t storage_bytes;
};
static size_t eo_view_node_offset(void){
    size_t alignment=_Alignof(struct eo_node);
    return (sizeof(struct eo_view)+alignment-1)/alignment*alignment;
}
static size_t eo_view_number_offset(unsigned nodes,unsigned strings){
    size_t offset=eo_view_node_offset()+(size_t)nodes*sizeof(struct eo_node)+strings;
    size_t alignment=_Alignof(int64_t);
    return (offset+alignment-1)/alignment*alignment;
}
/* side_bytes includes four little-endian uint16 counts when any wide value
 * exists. Empty sides consume no payload bytes. Native struct fields and node
 * size stay fixed; this is still a private, explicitly versioned local ABI. */
static size_t eo_view_allocation_size(unsigned nodes,unsigned strings,unsigned side_bytes){
    return eo_view_number_offset(nodes,strings)+side_bytes;
}
static unsigned eo_number_width(unsigned section){static const unsigned widths[4]={3,4,6,8};return widths[section];}
static unsigned eo_number_class(int64_t value){
    if(value>=-INT64_C(8388608)&&value<=INT64_C(8388607))return 0;
    if(value>=INT32_MIN&&value<=INT32_MAX)return 1;
    if(value>=-INT64_C(140737488355328)&&value<=INT64_C(140737488355327))return 2;
    return 3;
}
static unsigned eo_side_count(const struct eo_view *v,unsigned section){
    const unsigned char *side=(const unsigned char *)v->numbers;
    return (unsigned)side[2*section]|(unsigned)side[2*section+1]<<8;
}
static size_t eo_side_offset(const struct eo_view *v,unsigned section,unsigned index){
    size_t offset=8;
    for(unsigned i=0;i<section;i++)offset+=(size_t)eo_side_count(v,i)*eo_number_width(i);
    return offset+(size_t)index*eo_number_width(section);
}
static int64_t eo_number(const struct eo_view *v,int index){
    const struct eo_node *node=&v->nodes[index];
    if(node->kind==EO_BOOL)return node->text;
    if(node->kind!=EO_INT)return 0;
    if(!node->wide)return (int16_t)node->text;
    unsigned section=node->text>>14,slot=node->text&16383u,width=eo_number_width(section);
    const unsigned char *bytes=(const unsigned char *)v->numbers+eo_side_offset(v,section,slot);
    uint64_t bits=0;for(unsigned i=0;i<width;i++)bits|=(uint64_t)bytes[i]<<(8*i);
    if(width==8)return bits<=INT64_MAX?(int64_t)bits:-INT64_C(1)-(int64_t)~bits;
    return (int64_t)bits-((bits&(UINT64_C(1)<<(width*8-1)))?(INT64_C(1)<<(width*8)):0);
}
static void eo_zero(void *storage,size_t size){
    volatile unsigned char *p=storage;
    while(size--)*p++=0;
}
static void eo_view_dispose(struct eo_view *view){
    if(view){size_t size=view->storage_bytes;eo_zero(view,size);free(view);}
}
