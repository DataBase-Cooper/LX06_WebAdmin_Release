static int eo_event_byte(void *context,size_t offset){
    eo_event_work *w=context;if(offset>=w->length)return -1;
    return w->input->byte?w->input->byte(w->input->context,offset):(unsigned char)w->raw[offset];
}
static int eo_event_match(eo_event_work *w,size_t offset,const char *bytes,size_t length){
    if(offset>w->length||length>w->length-offset)return 0;
    for(size_t i=0;i<length;i++)if(eo_event_byte(w,offset+i)!=(unsigned char)bytes[i])return 0;
    return 1;
}
