static int eo_get(const struct eo_view *v,int o,const char *key) {
    if(o<0||v->nodes[o].kind!=EO_OBJECT)return -1;
    for(int k=v->nodes[o].child;k>=0;) {
        int value=v->nodes[k].next;
        if(!strcmp(v->strings+v->nodes[k].text,key))return value;
        k=v->nodes[value].next;
    }
    return -1;
}
static const char *eo_str(const struct eo_view *v,int t) {
    return t>=0&&v->nodes[t].kind==EO_STRING?v->strings+v->nodes[t].text:NULL;
}
static int eo_eq(const struct eo_view *v,int t,const char *s) {
    const char *p=eo_str(v,t);return p&&!strcmp(p,s);
}
static int eo_keys(const struct eo_view *v,int o,const char *allowed) {
    if(o<0||v->nodes[o].kind!=EO_OBJECT)return 0;
    for(int k=v->nodes[o].child;k>=0;) {
        const char *s=eo_str(v,k);char tag[68];
        /* Empty tags ("||") otherwise match the separator between allowed keys. */
        if(!s||!*s||strlen(s)>64)return 0;
        snprintf(tag,sizeof(tag),"|%s|",s);if(!strstr(allowed,tag))return 0;
        k=v->nodes[v->nodes[k].next].next;
    }
    return 1;
}
static int eo_int(const struct eo_view *v,int o,const char *key,int lo,int hi,int required) {
    int t=eo_get(v,o,key);return t<0?!required:
        v->nodes[t].kind==EO_INT&&eo_number(v,t)>=lo&&eo_number(v,t)<=hi;
}
static int eo_ident(const char *s) {
    if(!s||!*s||strlen(s)>32||!((*s>='a'&&*s<='z')||(*s>='A'&&*s<='Z')||*s=='_'))return 0;
    for(;*s;s++)if(!((*s>='a'&&*s<='z')||(*s>='A'&&*s<='Z')||(*s>='0'&&*s<='9')||*s=='_'))return 0;
    return 1;
}
static int eo_count(const struct eo_view *v,int t,int kind,int min,int max) {
    if(t<0||v->nodes[t].kind!=kind)return 0;
    int n=0;for(int k=v->nodes[t].child;k>=0;k=v->nodes[k].next)n++;
    if(kind==EO_OBJECT)n/=2;
    return n>=min&&n<=max;
}
static int eo_scalar(const struct eo_view *v,int t) {
    return t>=0&&(v->nodes[t].kind==EO_STRING||v->nodes[t].kind==EO_INT||
                 v->nodes[t].kind==EO_BOOL||v->nodes[t].kind==EO_NULL);
}
/* Only prior non-skippable steps may supply output. No dotted/deep paths. */
static int eo_value(const struct eo_view *v,int t,int inputs,const int *steps,int before) {
    if(eo_scalar(v,t))return 1;
    if(t<0)return 0;
    if(v->nodes[t].kind==EO_ARRAY) {
        /* A retains complete bounded rows. Schema/type/size evidence remains
         * with B K3. Unproven arrays are never execution permission. */
        if(!eo_count(v,t,EO_ARRAY,0,32))return 0;
        for(int r=v->nodes[t].child;r>=0;r=v->nodes[r].next) {
            if(!eo_count(v,r,EO_OBJECT,1,32))return 0;
            for(int k=v->nodes[r].child;k>=0;) {
                int a=v->nodes[k].next;
                if(!eo_ident(eo_str(v,k))||!eo_scalar(v,a))return 0;
                k=v->nodes[a].next;
            }
        }
        return 1;
    }
    if(!eo_keys(v,t,"|$ref|")||!eo_count(v,t,EO_OBJECT,1,1))return 0;
    const char *r=eo_str(v,eo_get(v,t,"$ref"));if(!r)return 0;
    if(!strncmp(r,"input.",6))return eo_ident(r+6)&&eo_get(v,inputs,r+6)>=0;
    if(strncmp(r,"steps.",6))return 0;
    const char *dot=strchr(r+6,'.');if(!dot||dot-r-6>32)return 0;
    char id[33];memcpy(id,r+6,(size_t)(dot-r-6));id[dot-r-6]=0;
    int found=-1;
    for(int i=0;i<before;i++)if(eo_eq(v,eo_get(v,steps[i],"id"),id))found=steps[i];
    if(found<0||eo_eq(v,eo_get(v,found,"policy"),"skip-if-done"))return 0;
    return !strcmp(dot,".text")||(!strncmp(dot,".json.",6)&&eo_ident(dot+6));
}
static int eo_map(const struct eo_view *v,int o,int inputs,const int *steps,int before) {
    if(o<0)return 1;
    if(!eo_count(v,o,EO_OBJECT,0,32))return 0;
    for(int k=v->nodes[o].child;k>=0;) {
        int t=v->nodes[k].next;
        if(!eo_ident(eo_str(v,k))||!eo_value(v,t,inputs,steps,before))return 0;
        k=v->nodes[t].next;
    }
    return 1;
}
static int eo_call(const struct eo_view *v,int o,int inputs,const int *steps,int before) {
    const char *action=eo_str(v,eo_get(v,o,"action"));
    if(!action||!*action||strlen(action)>128||strpbrk(action," \t\r\n/:"))return 0;
    int target=eo_get(v,o,"target");
    if(target>=0&&(!eo_str(v,target)||!*eo_str(v,target)||strlen(eo_str(v,target))>128))return 0;
    return eo_map(v,eo_get(v,o,"params"),inputs,steps,before);
}
static int eo_probe(const struct eo_view *v,int p,int step,int inputs,const int *steps,int before) {
    if(p<0)return 1;
    if(!eo_keys(v,p,"|action||target||params||all||timeout_ms||interval_ms||max_attempts|")||
       !eo_call(v,p,inputs,steps,before)||!eo_int(v,p,"timeout_ms",1,5000,1)||
       !eo_int(v,p,"interval_ms",100,1000,1)||!eo_int(v,p,"max_attempts",1,10,1))return 0;
    const char *a=eo_str(v,eo_get(v,step,"target")),*b=eo_str(v,eo_get(v,p,"target"));
    if((a||b)&&(!a||!b||strcmp(a,b)))return 0;
    int all=eo_get(v,p,"all");if(!eo_count(v,all,EO_ARRAY,1,8))return 0;
    for(int c=v->nodes[all].child;c>=0;c=v->nodes[c].next) {
        const char *f=eo_str(v,eo_get(v,c,"field"));
        if(!eo_keys(v,c,"|field||equals|")||!f||strncmp(f,"json.",5)||!eo_ident(f+5)||
           !eo_value(v,eo_get(v,c,"equals"),inputs,steps,before))return 0;
        int e=eo_get(v,c,"equals");
        if(v->nodes[e].kind==EO_ARRAY||v->nodes[e].kind==EO_NULL)return 0;
    }
    return 1;
}
/* Row properties use the original caps scalar/optional vocabulary. Only the
 * outer input accepts one bounded array; recursive structures stay rejected. */
static int eo_schema_at(const struct eo_view *v,int o,int row) {
    if(!eo_keys(v,o,row?"|type||min||max||enum||values||optional|":
        "|type||min||max||enum||required||items||minItems||maxItems|")||
       !eo_count(v,o,EO_OBJECT,1,9))return 0;
    int type=eo_get(v,o,"type"),is_enum=row&&eo_eq(v,type,"enum");
    if(!eo_eq(v,type,"string")&&!eo_eq(v,type,"int")&&!eo_eq(v,type,"bool")&&
       !is_enum&&(row||!eo_eq(v,type,"array")))return 0;
    int req=eo_get(v,o,row?"optional":"required");if(req>=0&&v->nodes[req].kind!=EO_BOOL)return 0;
    if(!eo_int(v,o,"min",INT_MIN,INT_MAX,0)||!eo_int(v,o,"max",INT_MIN,INT_MAX,0))return 0;
    int lo=eo_get(v,o,"min"),hi=eo_get(v,o,"max");
    if(lo>=0&&hi>=0&&eo_number(v,lo)>eo_number(v,hi))return 0;
    if(eo_eq(v,type,"string")&&hi>=0&&eo_number(v,hi)<1)return 0;
    if(eo_eq(v,type,"array")) {
        if(lo>=0||hi>=0||eo_get(v,o,"enum")>=0||!eo_int(v,o,"minItems",1,INT_MAX,1)||
           !eo_int(v,o,"maxItems",1,INT_MAX,1))return 0;
        int min=eo_get(v,o,"minItems"),max=eo_get(v,o,"maxItems"),item=eo_get(v,o,"items");
        if(eo_number(v,min)>eo_number(v,max)||!eo_keys(v,item,"|type||properties||additionalProperties|")||
           !eo_eq(v,eo_get(v,item,"type"),"object"))return 0;
        int extra=eo_get(v,item,"additionalProperties"),props=eo_get(v,item,"properties");
        if((extra>=0&&(v->nodes[extra].kind!=EO_BOOL||eo_number(v,extra)))||
           !eo_count(v,props,EO_OBJECT,0,EO_NODES))return 0;
        for(int k=v->nodes[props].child;k>=0;){int value=v->nodes[k].next;
            if(!eo_str(v,k)||!*eo_str(v,k)||!eo_schema_at(v,value,1))return 0;
            k=v->nodes[value].next;}
        return 1;
    }
    if(eo_get(v,o,"items")>=0||eo_get(v,o,"minItems")>=0||eo_get(v,o,"maxItems")>=0)return 0;
    if(!is_enum&&eo_get(v,o,"values")>=0)return 0;
    int en=eo_get(v,o,is_enum?"values":"enum");
    if(is_enum&&(en<0||eo_get(v,o,"enum")>=0||lo>=0||hi>=0))return 0;
    if(en>=0) {
        if(!eo_count(v,en,EO_ARRAY,1,32))return 0;
        for(int t=v->nodes[en].child;t>=0;t=v->nodes[t].next){
            if((is_enum&&v->nodes[t].kind!=EO_STRING&&v->nodes[t].kind!=EO_INT)||
               (eo_eq(v,type,"string")&&v->nodes[t].kind!=EO_STRING)||
               (eo_eq(v,type,"int")&&v->nodes[t].kind!=EO_INT)||
               (eo_eq(v,type,"bool")&&v->nodes[t].kind!=EO_BOOL))return 0;
            for(int q=v->nodes[en].child;q!=t;q=v->nodes[q].next)
                if(v->nodes[q].kind==v->nodes[t].kind&&
                   (v->nodes[t].kind==EO_STRING?!strcmp(eo_str(v,q),eo_str(v,t)):
                    eo_number(v,q)==eo_number(v,t)))return 0;
        }
    }
    return !eo_eq(v,type,"bool")||(lo<0&&hi<0);
}
static int eo_schema(const struct eo_view *v,int o){return eo_schema_at(v,o,0);}
static int eo_flow_valid(const struct eo_view *v,int root,eo_nfc nfc,void *ctx) {
    if(!eo_keys(v,root,"|version||flows|")||!eo_int(v,root,"version",1,1,1))return 0;
    int flows=eo_get(v,root,"flows");if(!eo_count(v,flows,EO_ARRAY,0,16))return 0;
    for(int f=v->nodes[flows].child;f>=0;f=v->nodes[f].next) {
        if(!eo_keys(v,f,"|name||inputs||steps||output|"))return 0;
        const char *name=eo_str(v,eo_get(v,f,"name"));
        if(!name||strpbrk(name,":/\\")||!nfc||nfc(ctx,name)!=1)return 0;
        /* Decoded UTF-8: controls include C1 (U+0080..U+009F), not just ASCII. */
        for(const unsigned char *p=(const unsigned char*)name;*p;p++)
            if(*p<32||*p==127||(*p==0xc2&&p[1]>=0x80&&p[1]<=0x9f))return 0;
        for(int prev=v->nodes[flows].child;prev!=f;prev=v->nodes[prev].next)
            if(eo_eq(v,eo_get(v,prev,"name"),name))return 0;
        int inputs=eo_get(v,f,"inputs");if(inputs>=0) {
            if(!eo_count(v,inputs,EO_OBJECT,0,16))return 0;
            for(int k=v->nodes[inputs].child;k>=0;) {
                int value=v->nodes[k].next;
                if(!eo_ident(eo_str(v,k))||!eo_schema(v,value))return 0;
                k=v->nodes[value].next;
            }
        }
        int ss=eo_get(v,f,"steps"),steps[16],count=0;
        if(!eo_count(v,ss,EO_ARRAY,1,16))return 0;
        for(int s=v->nodes[ss].child;s>=0;s=v->nodes[s].next) {
            if(!eo_keys(v,s,"|id||action||target||params||set||audio||policy||precondition||done||timeout_ms||retry||on_probe_unknown||restart||fallback|")||
               !eo_ident(eo_str(v,eo_get(v,s,"id")))||!eo_call(v,s,inputs,steps,count)||
               !eo_map(v,eo_get(v,s,"set"),inputs,steps,count)||!eo_int(v,s,"timeout_ms",1,900000,0))return 0;
            for(int i=0;i<count;i++)if(eo_eq(v,eo_get(v,steps[i],"id"),eo_str(v,eo_get(v,s,"id"))))return 0;
            int policy=eo_get(v,s,"policy"),unknown=eo_get(v,s,"on_probe_unknown");
            if(policy>=0&&!eo_eq(v,policy,"skip-if-done")&&!eo_eq(v,policy,"always-re-run")&&!eo_eq(v,policy,"force-restart"))return 0;
            if(unknown>=0&&!eo_eq(v,unknown,"fail")&&!eo_eq(v,unknown,"run-safe-action"))return 0;
            if(eo_eq(v,policy,"skip-if-done")&&eo_get(v,s,"done")<0)return 0;
            if(!eo_probe(v,eo_get(v,s,"precondition"),s,inputs,steps,count)||
               !eo_probe(v,eo_get(v,s,"done"),s,inputs,steps,count))return 0;
            int retry=eo_get(v,s,"retry");if(retry>=0&&(!eo_keys(v,retry,"|max_attempts||backoff_ms|")||
                !eo_int(v,retry,"max_attempts",1,3,1)||!eo_int(v,retry,"backoff_ms",0,2000,1)))return 0;
            int restart=eo_get(v,s,"restart");if((restart>=0)!=eo_eq(v,policy,"force-restart"))return 0;
            const char *extras[]={"restart","fallback"};
            for(int i=0;i<2;i++) {int r=eo_get(v,s,extras[i]);if(r<0)continue;
                if(!eo_keys(v,r,"|action||target||params|")||!eo_call(v,r,inputs,steps,count))return 0;
                const char *a=eo_str(v,eo_get(v,s,"target")),*b=eo_str(v,eo_get(v,r,"target"));
                if((a||b)&&(!a||!b||strcmp(a,b)))return 0;
            }
            int audio=eo_get(v,s,"audio");if(audio>=0) {
                if(!eo_keys(v,audio,"|mic||speaker||ring|"))return 0;
                const char *keys[]={"mic","speaker","ring"};for(int i=0;i<3;i++) {
                    int bit=eo_get(v,audio,keys[i]);if(bit>=0&&!eo_eq(v,bit,"open")&&!eo_eq(v,bit,"close"))return 0;
                }
            }
            steps[count++]=s;
        }
        int output=eo_get(v,f,"output");if(output>=0&&!eo_value(v,output,inputs,steps,count))return 0;
    }
    return 1;
}
