/* Local ABI 7. Signed INT16 stays inline. Wide integers retain their exact
 * signed value in dense 24/32/48/64-bit side sections. text stores two class
 * bits plus a 14-bit section index, preserving every original 8192-node case.
 * This changes number-side meaning; all C/Python consumers must rebuild. */
/* This is a compiler-local packed layout, never a wire representation.
 * Packed 16-bit member access is generated by the compiler on target ARM. */
struct __attribute__((packed)) eo_node {
    uint16_t text;int32_t child:14,next:14;uint32_t kind:3,wide:1;
};
_Static_assert(sizeof(struct eo_node)==6,"local sparse node ABI");
